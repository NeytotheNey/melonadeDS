#!/usr/bin/env python3
# Makes pc_gl_loader.h/.cpp from khronos/GLES3/gl32.h: a pointer for every GLES 3.2 function, named
# like the function through a #define, so the core's GL code compiles as it does against Android's
# libGLESv3. Run again only if gl32.h changes:
#
#   python desktop/gl/gen_gl_loader.py

import re
from pathlib import Path

here = Path(__file__).resolve().parent
header = (here / "khronos/GLES3/gl32.h").read_text()

names = re.findall(r"^GL_APICALL\b.*?GL_APIENTRY\s+(gl\w+)\s*\(", header, re.M)
names = list(dict.fromkeys(names))

def pfn(name):
    return "PFN" + name.upper() + "PROC"

h = [
    "// Generated by gen_gl_loader.py from khronos/GLES3/gl32.h, don't edit",
    "#pragma once",
    "",
]
for n in names:
    h.append(f"extern {pfn(n)} pcgl_{n};")
    h.append(f"#define {n} pcgl_{n}")
h += [
    "",
    "// loads every pointer through getProc, returns how many came back null",
    "int PcGl_Load(void* (*getProc)(const char* name));",
    "",
]

c = [
    "// Generated by gen_gl_loader.py from khronos/GLES3/gl32.h, don't edit",
    '#include "pc_gl.h"',
    "",
]
for n in names:
    c.append(f"{pfn(n)} pcgl_{n} = nullptr;")
c += [
    "",
    "int PcGl_Load(void* (*getProc)(const char* name))",
    "{",
    "    int missing = 0;",
]
for n in names:
    c.append(f'    pcgl_{n} = ({pfn(n)}) getProc("{n}"); missing += pcgl_{n} == nullptr;')
c += [
    "    return missing;",
    "}",
    "",
]

(here / "pc_gl_loader.h").write_text("\n".join(h))
(here / "pc_gl_loader.cpp").write_text("\n".join(c))
print(f"{len(names)} functions")
