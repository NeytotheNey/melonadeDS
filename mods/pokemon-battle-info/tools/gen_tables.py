"""Generates the mod's data tables in pbi/. Run once; the output is kept in the repo, the ROM and the CSVs aren't.

  py -I -X utf8 gen_tables.py --rom <White 2 .nds> --csv-dir <folder with the PokeAPI CSVs> --font <LuaFont.h> --out ../pbi

Move type and category come from the White 2 ROM (read-only), from the move NARC a/0/2/1. Each file in it is one move:
byte 0 type, byte 1 effect group, byte 2 category (0 status, 1 physical, 2 special), byte 3 power, byte 4 accuracy, byte 5 PP,
and a 32-bit flag word at 0x20 with the sound flag at bit 8. Only type, category and the sound moves are written out.

Types per species come from the ROM too, from the personal NARC a/0/1/6: byte 6 and 7 are the types, the u16 at 0x1C is the
file of a species' first alternate form and byte 0x20 is how many forms it has.

Pokemon and ability names come from PokeAPI (data/v2/csv/pokemon_species_names.csv and ability_names.csv, English rows),
https://github.com/PokeAPI/pokeapi. Text widths come from the font the app draws with.
"""
import argparse
import csv
import os
import re
import struct

MOVE_COUNT = 559  # 1 Pound to 559 Fusion Bolt is all of Gen 5
MOVE_FLAGS = 0x20
SOUND_FLAG = 1 << 8
# Spot check for the flag: Growl, Roar, Sing, Supersonic, Screech, Hyper Voice, Bug Buzz, Round, Echoed Voice, Relic Song, Snarl
SOUND_SAMPLE = {45, 46, 47, 48, 103, 304, 405, 496, 497, 547, 555}
SPECIES_COUNT = 649
ABILITY_COUNT = 164  # 164 Teravolt
ENGLISH = "9"
# The font has ASCII only, and PokeAPI writes these with symbols. Egg is species 650 in the game.
NAME_FIXES = {"Nidoran♀": "Nidoran F", "Nidoran♂": "Nidoran M"}


def read_narc_from_rom(path, narc_path):
    with open(path, "rb") as f:
        rom = f.read()
    fnt_off, _, fat_off, _ = struct.unpack_from("<IIII", rom, 0x40)

    def directory(dir_id):
        entry = fnt_off + (dir_id & 0xFFF) * 8
        table_off, first_file = struct.unpack_from("<IH", rom, entry)
        pos, file_id, out = fnt_off + table_off, first_file, {}
        while True:
            head = rom[pos]
            pos += 1
            if head == 0:
                return out
            name = rom[pos:pos + (head & 0x7F)].decode("ascii")
            pos += head & 0x7F
            if head & 0x80:
                out[name] = ("dir", struct.unpack_from("<H", rom, pos)[0])
                pos += 2
            else:
                out[name] = ("file", file_id)
                file_id += 1

    node = ("dir", 0xF000)
    for part in narc_path.split("/"):
        node = directory(node[1])[part]
    start, end = struct.unpack_from("<II", rom, fat_off + node[1] * 8)
    return rom[start:end]


def narc_files(narc):
    if narc[:4] != b"NARC":
        raise SystemExit("not a NARC")
    pos = struct.unpack_from("<H", narc, 0x0C)[0]
    sections = {}
    for _ in range(struct.unpack_from("<H", narc, 0x0E)[0]):
        magic, size = narc[pos:pos + 4], struct.unpack_from("<I", narc, pos + 4)[0]
        sections[magic] = (pos, size)
        pos += size
    btaf, gmif = sections[b"BTAF"][0], sections[b"GMIF"][0] + 8
    count = struct.unpack_from("<H", narc, btaf + 8)[0]
    return [narc[gmif + s:gmif + e] for s, e in (struct.unpack_from("<II", narc, btaf + 12 + i * 8) for i in range(count))]


def rows(values, per_line=24):
    return "\n".join(
        "  " + ",".join(str(v) for v in values[i:i + per_line]) + ",  -- " + str(i + 1)
        for i in range(0, len(values), per_line)
    )


def names_from(path, id_column):
    out = {}
    with open(path, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            if row["local_language_id"] == ENGLISH:
                out[int(row[id_column])] = row["name"]
    return out


def ascii_name(name):
    name = NAME_FIXES.get(name, name).replace("’", "'")
    if not name.isascii():
        raise SystemExit("non-ASCII name: " + name)
    return '"' + name.replace('"', '\\"') + '"'


def write(path, text):
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print(os.path.basename(path), len(text), "bytes")


def gen_moves(rom, out):
    files = narc_files(read_narc_from_rom(rom, "a/0/2/1"))
    if len(files) <= MOVE_COUNT:
        raise SystemExit("move NARC has only %d files" % len(files))
    types = [files[i][0] for i in range(1, MOVE_COUNT + 1)]
    cats = [files[i][2] for i in range(1, MOVE_COUNT + 1)]
    if max(types) > 16 or max(cats) > 2:
        raise SystemExit("unexpected type or category value")
    sound = [i for i in range(1, MOVE_COUNT + 1) if struct.unpack_from("<I", files[i], MOVE_FLAGS)[0] & SOUND_FLAG]
    if not SOUND_SAMPLE <= set(sound):
        raise SystemExit("sound flag doesn't match the known sound moves")
    write(os.path.join(out, "data_moves.lua"), (
        "-- Generated by tools/gen_tables.py from the move data of the White 2 ROM (a/0/2/1). Don't edit by hand.\n"
        "-- Index is the move ID, 1 to %d. type is the game's Gen 5 type ID; category: 0 status, 1 physical, 2 special.\n"
        "-- sound holds the moves with the sound flag, the ones Soundproof stops.\n"
        "return {\n  type = {\n%s\n  },\n  category = {\n%s\n  },\n  sound = { %s },\n}\n"
    ) % (MOVE_COUNT, rows(types), rows(cats), ", ".join("[%d] = true" % i for i in sound)))
    return files


def gen_personal(rom, out):
    files = narc_files(read_narc_from_rom(rom, "a/0/1/6"))
    type1 = [files[i][6] for i in range(1, SPECIES_COUNT + 1)]
    type2 = [files[i][7] for i in range(1, SPECIES_COUNT + 1)]
    if max(type1) > 16 or max(type2) > 16:
        raise SystemExit("unexpected personal type value")
    forms = []
    for species in range(1, SPECIES_COUNT + 1):
        first, count = struct.unpack_from("<H", files[species], 0x1C)[0], files[species][0x20]
        entries = []
        for form in range(1, count):
            index = first + form - 1
            if first and index < len(files) and tuple(files[index][6:8]) != tuple(files[species][6:8]):
                entries.append("[%d] = { %d, %d }" % (form, files[index][6], files[index][7]))
        if entries:
            forms.append("    [%d] = { %s }," % (species, ", ".join(entries)))
    write(os.path.join(out, "data_personal.lua"), (
        "-- Generated by tools/gen_tables.py from the personal data of the White 2 ROM (a/0/1/6). Don't edit by hand.\n"
        "-- Index is the national dex number; the values are the game's Gen 5 type IDs. forms lists only the forms whose\n"
        "-- types differ from the species' own.\n"
        "return {\n  type1 = {\n%s\n  },\n  type2 = {\n%s\n  },\n  forms = {\n%s\n  },\n}\n"
    ) % (rows(type1), rows(type2), "\n".join(forms)))


def gen_species(csv_dir, out):
    names = names_from(os.path.join(csv_dir, "pokemon_species_names.csv"), "pokemon_species_id")
    values = [ascii_name(names[i]) for i in range(1, SPECIES_COUNT + 1)]
    write(os.path.join(out, "data_species.lua"), (
        "-- Generated by tools/gen_tables.py from PokeAPI pokemon_species_names.csv. Don't edit by hand.\n"
        "-- Index is the national dex number, ASCII spellings only. 650 is the game's egg.\n"
        "return {\n%s\n  \"Egg\",\n}\n"
    ) % rows(values, 10))


def gen_abilities(csv_dir, out):
    names = names_from(os.path.join(csv_dir, "ability_names.csv"), "ability_id")
    values = [ascii_name(names[i]) for i in range(1, ABILITY_COUNT + 1)]
    write(os.path.join(out, "data_abilities.lua"), (
        "-- Generated by tools/gen_tables.py from PokeAPI ability_names.csv. Don't edit by hand.\n"
        "-- Index is the Gen 5 ability ID.\n"
        "return {\n%s\n}\n"
    ) % rows(values, 8))


def gen_font(font_path, out):
    src = open(font_path, encoding="utf-8").read()
    body = src[src.index("kLuaFont[] = {") + 14:]
    body = body[:body.index("};")]
    font = [int(v, 0) for v in re.findall(r"0x[0-9A-Fa-f]+|\d+", re.sub(r"/\*.*?\*/|//[^\n]*", "", body, flags=re.S))]
    # Pen advance in overlay pixels (2 per DS pixel), blank glyphs are 6 wide and the others get a pixel of space on each side
    advance = [(font[(c - 0x10) * 16] + 2) if font[(c - 0x10) * 16] else 6 for c in range(32, 127)]
    write(os.path.join(out, "font.lua"), (
        "-- Generated by tools/gen_tables.py from app/src/main/cpp/scripting/LuaFont.h. Don't edit by hand.\n"
        "-- Pen advance per character in overlay pixels (2 per DS pixel), index is the character code minus 31.\n"
        "return {\n%s\n}\n"
    ) % rows(advance, 32))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--rom", required=True)
    p.add_argument("--csv-dir", required=True)
    p.add_argument("--font", required=True)
    p.add_argument("--out", required=True)
    args = p.parse_args()
    files = gen_moves(args.rom, args.out)
    gen_personal(args.rom, args.out)
    gen_species(args.csv_dir, args.out)
    gen_abilities(args.csv_dir, args.out)
    gen_font(args.font, args.out)
    # Spot check to read by eye: Ember, Earthquake, Thunder Wave, Curse, Bite, Karate Chop, Sand Attack, Charm
    for move in (52, 89, 86, 174, 44, 2, 28, 204):
        d = files[move]
        print("move %3d: type %2d category %d power %3d accuracy %3d pp %2d" % (move, d[0], d[2], d[3], d[4], d[5]))


if __name__ == "__main__":
    main()
